"use client";

import { useMemo, useState } from "react";
import {
  BellRing,
  CheckCircle2,
  PhoneCall,
  ShieldCheck,
  SlidersHorizontal,
} from "lucide-react";
import type { AlertSeverity, SafetyAlert } from "@caretwin/contracts";
import { countOpenBySeverity } from "@caretwin/domain";
import { formatDateTime } from "@caretwin/shared";
import { ApiClientError, apiRequest, errorMessage } from "@/lib/api";
import { useSession } from "@/lib/session";
import { useApi } from "@/lib/use-api";
import { PageHeader } from "@/components/ui/cards";
import { Badge, SeverityBadge } from "@/components/ui/badges";
import {
  AccessRestricted,
  EmptyState,
  ErrorState,
  InlineMessage,
  LoadingBlock,
  PageSkeleton,
} from "@/components/ui/feedback";
import { Tabs } from "@/components/ui/tabs";
import { AlertCard } from "@/components/workspace/alert-card";

type Tab = "open" | "acknowledged" | "resolved" | "all";

const severityOrder: AlertSeverity[] = ["critical", "urgent", "moderate", "info"];

export default function AlertsPage() {
  const { patientId, selectedUser } = useSession();
  const state = useApi<SafetyAlert[]>(
    patientId ? `/patients/${patientId}/alerts` : null,
  );
  const [tab, setTab] = useState<Tab>("open");
  const [severity, setSeverity] = useState<"all" | AlertSeverity>("all");
  const [busyId, setBusyId] = useState<string | null>(null);
  const [message, setMessage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const alerts = useMemo(() => state.data ?? [], [state.data]);
  const isClinician = selectedUser?.role === "clinician";

  const counts = useMemo(() => {
    const open = alerts.filter((item) => item.status === "open");
    return {
      open: open.length,
      acknowledged: alerts.filter((item) => item.status === "acknowledged").length,
      resolved: alerts.filter((item) => item.status === "resolved").length,
      all: alerts.length,
      severity: countOpenBySeverity(alerts),
    };
  }, [alerts]);

  const filtered = useMemo(() => {
    const list = alerts.filter((alert) => (tab === "all" ? true : alert.status === tab));
    return severity === "all"
      ? list
      : list.filter((alert) => alert.severity === severity);
  }, [alerts, tab, severity]);

  async function acknowledge(alertId: string, note: string) {
    if (!patientId || !selectedUser) return;
    setBusyId(alertId);
    setError(null);
    setMessage(null);
    try {
      const result = await apiRequest<{ eventId: string }>(
        `/patients/${patientId}/alerts/${alertId}/acknowledge`,
        { method: "POST", userId: selectedUser.id, body: { note } },
      );
      setMessage(`Alert acknowledged and recorded in the timeline (${result.eventId}).`);
      state.refresh();
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setBusyId(null);
    }
  }

  async function resolve(alertId: string, note: string) {
    if (!patientId || !selectedUser) return;
    setBusyId(alertId);
    setError(null);
    setMessage(null);
    try {
      const result = await apiRequest<{ eventId: string; twinVersion: number }>(
        `/patients/${patientId}/alerts/${alertId}/resolve`,
        { method: "POST", userId: selectedUser.id, body: { note } },
      );
      setMessage(
        `Alert resolved and recorded in the timeline (${result.eventId}). Twin v${result.twinVersion}.`,
      );
      state.refresh();
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setBusyId(null);
    }
  }

  if (state.loading && !state.data) return <PageSkeleton />;
  if (state.error instanceof ApiClientError && state.error.status === 403) {
    return (
      <AccessRestricted
        title="Safety alerts are not shared with this role"
        description="This caregiver identity has no active alert scope. When sharing is active, caregivers can see open concerns but cannot acknowledge or resolve them."
      />
    );
  }
  if (state.error) return <ErrorState error={state.error} onRetry={state.refresh} />;

  return (
    <div className="animate-fade-in">
      <PageHeader
        eyebrow="Safety alert center"
        title="Rule-based concerns, with provenance."
        description="Alerts are generated by clinician-configured deterministic thresholds. They are not diagnoses, and acknowledging one does not treat the patient."
        actions={
          <div className="flex flex-wrap gap-1.5">
            <Badge tone={counts.open ? "rose" : "teal"}>{counts.open} open</Badge>
            <Badge tone="blue">{counts.acknowledged} acknowledged</Badge>
          </div>
        }
      />

      {message && (
        <InlineMessage tone="success" className="mb-4">
          {message}
        </InlineMessage>
      )}
      {error && (
        <InlineMessage tone="error" className="mb-4">
          {error}
        </InlineMessage>
      )}

      <div className="mb-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
        {severityOrder.map((level) => (
          <button
            key={level}
            onClick={() => {
              setSeverity(severity === level ? "all" : level);
              setTab("open");
            }}
            aria-pressed={severity === level}
            className={`rounded-xl border bg-white p-4 text-left transition-colors ${
              severity === level
                ? "border-care-400 ring-1 ring-care-500/20"
                : "border-slate-200 hover:border-slate-300"
            }`}
          >
            <div className="flex items-center justify-between">
              <SeverityBadge severity={level} />
              <span className="font-mono text-[0.6rem] text-slate-400">open</span>
            </div>
            <p className="mt-2 text-xl font-semibold text-navy-950">
              {counts.severity[level]}
            </p>
            <p className="text-[0.64rem] text-slate-500">
              {level === "critical"
                ? "Requires urgent human review"
                : level === "urgent"
                  ? "Prompt review recommended"
                  : level === "moderate"
                    ? "Review at next contact"
                    : "Informational flag"}
            </p>
          </button>
        ))}
      </div>

      <div className="grid gap-4 lg:grid-cols-[1.5fr_1fr]">
        <div className="min-w-0">
          <Tabs
            className="mb-3"
            items={[
              { value: "open", label: "Open", count: counts.open },
              { value: "acknowledged", label: "Acknowledged", count: counts.acknowledged },
              { value: "resolved", label: "Resolved", count: counts.resolved },
              { value: "all", label: "All", count: counts.all },
            ]}
            value={tab}
            onChange={setTab}
          />
          {severity !== "all" && (
            <div className="mb-3 flex items-center gap-2 text-[0.66rem] text-slate-500">
              Filtering severity: <Badge tone="slate">{severity}</Badge>
              <button
                onClick={() => setSeverity("all")}
                className="font-semibold text-care-700 hover:text-care-800"
              >
                Clear
              </button>
            </div>
          )}

          {state.loading ? (
            <LoadingBlock label="Loading alerts" />
          ) : filtered.length === 0 ? (
            <EmptyState
              icon={<ShieldCheck className="h-4 w-4" />}
              title="No alerts in this view"
              description="Try another status or severity filter."
            />
          ) : (
            <div className="space-y-2.5">
              {filtered.map((alert) => (
                <AlertCard
                  key={alert.id}
                  alert={alert}
                  canAcknowledge={isClinician}
                  onAcknowledge={(note) => void acknowledge(alert.id, note)}
                  acknowledging={busyId === alert.id}
                  canResolve={isClinician}
                  onResolve={(note) => void resolve(alert.id, note)}
                  resolving={busyId === alert.id}
                />
              ))}
            </div>
          )}
        </div>

        <div className="min-w-0 space-y-4">
          <div className="rounded-2xl border border-rose-200 bg-rose-50/60 p-4">
            <p className="flex items-center gap-2 text-xs font-semibold text-rose-800">
              <PhoneCall className="h-4 w-4" /> If this is an emergency
            </p>
            <p className="mt-1.5 text-[0.72rem] leading-relaxed text-rose-900/80">
              If symptoms feel severe or are worsening quickly, contact local emergency
              services or the care team now. Do not wait for app-based review or alert
              acknowledgment.
            </p>
          </div>

          <div className="rounded-2xl border border-slate-200 bg-white p-4">
            <p className="flex items-center gap-2 text-xs font-semibold text-navy-950">
              <SlidersHorizontal className="h-4 w-4 text-care-700" /> How alerts are produced
            </p>
            <ul className="mt-2 space-y-2 text-[0.68rem] leading-relaxed text-slate-600">
              <li className="flex gap-2">
                <span className="mt-1 h-1 w-1 shrink-0 rounded-full bg-care-500" />
                Six deterministic rules cover chest pain, breathlessness, fever, adherence,
                pain escalation and check-in gaps.
              </li>
              <li className="flex gap-2">
                <span className="mt-1 h-1 w-1 shrink-0 rounded-full bg-care-500" />
                Thresholds are configured by a clinician and stored with the patient record.
              </li>
              <li className="flex gap-2">
                <span className="mt-1 h-1 w-1 shrink-0 rounded-full bg-care-500" />
                Each alert keeps its evidence source, rule id and rationale.
              </li>
              <li className="flex gap-2">
                <span className="mt-1 h-1 w-1 shrink-0 rounded-full bg-care-500" />
                Only a clinician can acknowledge an alert. Acknowledgment is review, not
                diagnosis.
              </li>
            </ul>
          </div>

          <div className="rounded-2xl border border-slate-200 bg-white p-4">
            <p className="flex items-center gap-2 text-xs font-semibold text-navy-950">
              <BellRing className="h-4 w-4 text-care-700" /> Actor boundary
            </p>
            <div className="mt-2 space-y-2 text-[0.68rem] text-slate-600">
              <p className="flex items-start gap-2">
                <CheckCircle2 className="mt-0.5 h-3 w-3 shrink-0 text-care-600" />
                {isClinician
                  ? "You are signed in as a clinician and can acknowledge open alerts."
                  : "This role can inspect alerts but cannot acknowledge them."}
              </p>
              <p className="text-[0.64rem] text-slate-400">
                {counts.open > 0
                  ? `${counts.open} open alert${counts.open === 1 ? "" : "s"} currently awaiting review.`
                  : "No open alerts right now."}
              </p>
            </div>
          </div>

          {alerts[0] && (
            <p className="text-[0.62rem] leading-relaxed text-slate-400">
              Latest rule event{" "}
              <span className="font-mono">{alerts[0].ruleId}</span> at{" "}
              {formatDateTime(alerts[0].createdAt)}.
            </p>
          )}
        </div>
      </div>
    </div>
  );
}
